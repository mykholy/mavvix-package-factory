"""Post an idempotent, bounded weekly discovery digest to this repository's Issues.

The publisher has Issues-write but cannot merge code or create releases.
"""
import argparse
import json
import os
import re
import sys
from datetime import datetime, timezone
from pathlib import Path
from typing import Any
from urllib.error import HTTPError, URLError
from urllib.parse import urlencode
from urllib.request import Request, urlopen

REPO_PATTERN = re.compile(r"^[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+$")
VALID_GITHUB_ISSUE = re.compile(r"^https://github[.]com/[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+/issues/[1-9][0-9]*$")


def digest_title(now: datetime) -> str:
    year, week, _ = now.isocalendar()
    return f"[Research Digest] {year}-W{week:02d}"


def safe_title(title: str) -> str:
    """Prevent public source titles from creating Markdown references/mentions."""
    return (
        " ".join(title.split())[:150]
        .replace("\\", "\\\\")
        .replace("[", "\\[")
        .replace("]", "\\]")
        .replace("@", "@\u200b")
        .replace("<", "&lt;")
        .replace(">", "&gt;")
    )


def render_digest(report: dict[str, Any], *, run_url: str, analysis: str = "") -> str:
    if report.get("mode") != "github_live":
        raise ValueError("Refusing to publish synthetic fixtures as real research")
    if report.get("schema_version", 0) < 2:
        raise ValueError("Research report must include precision screening metadata")
    if not run_url.startswith("https://github.com/"):
        raise ValueError("Run URL must point to GitHub")
    entries = report.get("opportunities")
    if not isinstance(entries, list):
        raise ValueError("Report missing opportunities")
    lines = [
        "# Weekly developer problem discovery (unvalidated)",
        "",
        f"**Source:** [GitHub Actions discovery run]({run_url})",
        f"**Generated:** {safe_title(str(report.get('generated_at', 'unknown')))}",
        f"**Search window:** {safe_title(str(report.get('since', 'unknown')))} onward (by *updated* date)",
        "",
        "> GitHub Issues are research leads, NOT proof of unmet market demand.",
        "> All ranks below are heuristics (maximum 35), NOT a validated 100-point opportunity score.",
        "> Automated analysis cannot approve package development or publication.",
        "",
    ]
    creation = report.get("issue_creation_metrics")
    if isinstance(creation, dict) and all(
        isinstance(creation.get(key), int) and creation[key] >= 0
        for key in ("created_within_window", "created_before_window", "unknown_created_at")
    ):
        lines.extend([
            "## New issues vs recently updated issues",
            "",
            f"- Created within the search window (UTC): {creation['created_within_window']}",
            f"- Created earlier, updated in the window: {creation['created_before_window']}",
            f"- Unknown creation time: {creation['unknown_created_at']}",
            "- Counts are distinct sampled issue URLs, not proof of demand.",
            "",
        ])
    if report.get("warnings"):
        lines.extend(["## Collection warnings", ""])
        lines.extend(f"- {safe_title(str(w))}" for w in report["warnings"][:12])
        lines.append("")
    if analysis.strip():
        lines.extend([
            "## AI-assisted triage — unverified hypotheses",
            "",
            "> Based on a bounded sample of issue titles, not on full source verification.",
            "> Its statements are hypotheses until a researcher checks the linked threads.",
            "",
            analysis.strip()[:6500].replace("@", "@\u200b"),
            "",
        ])
    lines.extend(["## Samples by topic", ""])
    for op in entries[:12]:
        if not isinstance(op, dict):
            continue
        lines.extend([
            f"### {safe_title(str(op.get('title', '(untitled)')))}",
            "",
            (
                f"**Retained:** {int(op.get('issue_count', 0))}; "
                f"**Sampled:** {int(op.get('sampled_results', 0))}; "
                f"**Excluded:** {int(op.get('filtered_results', 0))}; "
                f"**Signal:** {min(35, max(0, int(op.get('signal_score', 0))))}/35."
            ),
            "",
        ])
        for evidence in (op.get("evidence") or [])[:6]:
            if not isinstance(evidence, dict):
                continue
            url = str(evidence.get("url") or "")
            if VALID_GITHUB_ISSUE.fullmatch(url):
                lines.append(f"- [{safe_title(str(evidence.get('title', 'GitHub issue')))}]({url})")
        lines.append("")
    lines.extend([
        "## Next decision gate",
        "",
        "Before anyone builds a package, independently confirm multiple primary sources,",
        "the status of maintained alternatives, the gap against FlowGuard/AccessProof/LeakProof,",
        "and a documented human-reviewed opportunity score. Prefer upstream fixes where suitable.",
        "",
        "_Generated by a bounded GitHub Actions research bot. No software was published._",
    ])
    return "\n".join(lines)


class GitHubIssuePublisher:
    def __init__(self, token: str, repo: str, *, opener=urlopen) -> None:
        if not token:
            raise ValueError("Missing token for publishing")
        if not REPO_PATTERN.fullmatch(repo):
            raise ValueError("Invalid repository name")
        self.token = token
        self.repo = repo
        self.opener = opener

    def _request(self, method: str, path: str, data: dict | None = None) -> Any:
        url = f"https://api.github.com/repos/{self.repo}/{path}"
        raw = json.dumps(data).encode("utf-8") if data is not None else None
        request = Request(url, data=raw, method=method, headers={
            "Authorization": f"Bearer {self.token}",
            "Accept": "application/vnd.github+json",
            "Content-Type": "application/json",
            "X-GitHub-Api-Version": "2022-11-28",
            "User-Agent": "mavvix-research-publisher",
        })
        try:
            with self.opener(request, timeout=20) as response:
                result = json.load(response)
        except HTTPError as exc:
            raise RuntimeError(f"GitHub issues API returned HTTP {exc.code}") from exc
        except (URLError, TimeoutError, ValueError) as exc:
            raise RuntimeError(f"GitHub issues API failed: {type(exc).__name__}") from exc
        return result

    def upsert(self, title: str, body: str) -> tuple[str, str]:
        # Repository Issues API is immediately consistent, unlike search indexing.
        # Cap pagination to prevent unlimited write-oriented automation.
        found = None
        for page in range(1, 6):
            issues = self._request("GET", f"issues?{urlencode({'state':'all','per_page':100,'page':page})}")
            if not isinstance(issues, list):
                raise RuntimeError("Unexpected Issues API response")
            for issue in issues:
                if "pull_request" not in issue and issue.get("title") == title:
                    found = issue
                    break
            if found or len(issues) < 100:
                break
        if found:
            if found.get("body") == body:
                return "unchanged", str(found.get("html_url", ""))
            result = self._request("PATCH", f"issues/{int(found['number'])}", {"body": body})
            return "updated", str(result["html_url"])
        result = self._request("POST", "issues", {"title": title, "body": body})
        return "created", str(result["html_url"])


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--report", type=Path, required=True)
    parser.add_argument("--analysis", type=Path)
    parser.add_argument("--run-url", required=True)
    parser.add_argument("--repo", default=os.environ.get("GITHUB_REPOSITORY", ""))
    parser.add_argument("--dry-run", action="store_true")
    args = parser.parse_args(argv)
    try:
        report = json.loads(args.report.read_text(encoding="utf-8"))
        analysis = args.analysis.read_text(encoding="utf-8") if args.analysis and args.analysis.exists() else ""
        body = render_digest(report, run_url=args.run_url, analysis=analysis)
        title = digest_title(datetime.now(timezone.utc))
        if args.dry_run:
            print(f"{title}\n\n{body}")
        else:
            client = GitHubIssuePublisher(os.environ.get("GITHUB_TOKEN", ""), args.repo)
            action, url = client.upsert(title, body)
            print(f"Weekly digest {action}: {url}")
    except (OSError, ValueError, RuntimeError, json.JSONDecodeError) as exc:
        print(f"Digest failed: {exc}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
